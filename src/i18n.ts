export function getTranslation(keyOrText: string, lang: Language): string {
  if (!keyOrText) return '';
  if (lang === 'en') {
    return TRANSLATIONS.en[keyOrText] || keyOrText;
  }

  // 1. Direct translation key lookup
  if (TRANSLATIONS[lang]?.[keyOrText]) {
    return TRANSLATIONS[lang][keyOrText];
  }

  // 2. Normalized common words/phrases lookup
  const normalized = keyOrText.trim().toLowerCase();
  if (COMMON_WORDS[lang]?.[normalized]) {
    return COMMON_WORDS[lang][normalized];
  }

  // 3. English key fallback
  if (TRANSLATIONS.en?.[keyOrText]) {
    // If we have an english string for this key, check if that english text is in COMMON_WORDS
    const engText = TRANSLATIONS.en[keyOrText].toLowerCase();
    if (COMMON_WORDS[lang]?.[engText]) {
      return COMMON_WORDS[lang][engText];
    }
  }

  return TRANSLATIONS.en[keyOrText] || keyOrText;
}

